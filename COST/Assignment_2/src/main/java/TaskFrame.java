    private Integer validateAndGetTaskId() {
    try {
        // Grab text, strip hidden spaces, and try converting to a number
        return Integer.parseInt(txtTaskId.getText().trim());
    } catch (NumberFormatException e) {
        // If it fails (e.g., user typed letters), show an alert box
        JOptionPane.showMessageDialog(this, 
            "Invalid Input: Task ID must be a numeric value!", 
            "Input Error", 
            JOptionPane.ERROR_MESSAGE);
        return null; // Return null to signal that the input was invalid
    }
}
