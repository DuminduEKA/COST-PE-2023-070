    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
    Integer id = validateAndGetTaskId(); // Validates input before DB operation
    if (id == null) return;

    String title = txtTaskTitle.getText().trim();
    String status = comboStatus.getSelectedItem().toString();

    if (title.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Task Title cannot be empty!", "Validation Error", JOptionPane.WARNING_MESSAGE);
        return;
    }

    Task task = new Task(id, title, status);
    if (taskDAO.addTask(task)) {
        JOptionPane.showMessageDialog(this, "Task added successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
        clearFields();
    }    // TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
      Integer id = validateAndGetTaskId();
    if (id == null) return;

    Task task = taskDAO.searchTask(id);
    if (task != null) {
        txtTaskTitle.setText(task.getTaskTitle());
        comboStatus.setSelectedItem(task.getStatus());
    } else {
        JOptionPane.showMessageDialog(this, "Task not found with ID: " + id, "Not Found", JOptionPane.INFORMATION_MESSAGE);
    }  // TODO add your handling code here:
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
   Integer id = validateAndGetTaskId();
    if (id == null) return;

    String title = txtTaskTitle.getText().trim();
    String status = comboStatus.getSelectedItem().toString();

    if (title.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Task Title cannot be empty!", "Validation Error", JOptionPane.WARNING_MESSAGE);
        return;
    }

    Task task = new Task(id, title, status);
    if (taskDAO.updateTask(task)) {
        JOptionPane.showMessageDialog(this, "Task updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
        clearFields();
    } else {
        JOptionPane.showMessageDialog(this, "Update failed. Task ID may not exist.", "Error", JOptionPane.ERROR_MESSAGE);
    }     // TODO add your handling code here:
    }//GEN-LAST:event_btnUpdateActionPerformed

